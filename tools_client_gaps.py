"""Compares the client's message catalogue with what this server answers.

Reads notes/client-protocol.json (produced by tools_client_dump.py) and the
server's own InboundMsg/OutboundMsg enums plus the live router, then writes
notes/client-gaps.md: the requests the client can send that nothing handles.

    python tools_client_gaps.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)

OUT = os.path.join(ROOT, "notes", "client-gaps.md")
PROTOCOL = os.path.join(ROOT, "notes", "client-protocol.json")


def simple(name):
    return name.rsplit(".", 1)[-1].split("+")[-1]


def looks_like_request(full_name, enum_names):
    """A client-sent message: named `...outgoing...`, or already in InboundMsg."""
    name = simple(full_name)
    if name in enum_names:
        return True
    return ".outgoing." in full_name or full_name.endswith(".outgoing")


def main():
    from ptcgo.network import message_names as names
    from ptcgo.packets.router import PacketRouter

    class _Client:
        addr = ("127.0.0.1", 1)
        player = None

        async def send_packet(self, *args, **kwargs):
            return True

    handled = set(PacketRouter(_Client()).handlers)
    inbound = {m.value for m in names.InboundMsg}
    outbound = {m.value for m in names.OutboundMsg}
    catalogue = json.load(open(PROTOCOL, encoding="utf-8"))["messages"]

    declared_unhandled = sorted(name for name in inbound if name not in handled)
    requests = {full: data for full, data in catalogue.items()
                if looks_like_request(full, inbound)}
    silent = sorted({simple(full) for full in requests} - handled)

    with open(OUT, "w", encoding="utf-8") as out:
        out.write("# Client messages this server does not answer\n\n")
        out.write("Generated by `tools_client_gaps.py` from `notes/client-protocol.json` "
                  "and the running router. A message here is one the client can send and "
                  "will wait on: the answer is either a handler with the right shape or an "
                  "explicit error, never silence.\n\n")
        out.write(f"- client message DTOs known: **{len(catalogue)}**\n")
        out.write(f"- inbound names declared by the server: **{len(inbound)}**, "
                  f"handled: **{len(inbound & handled)}**\n")
        out.write(f"- client request types recognised (by name or `outgoing` namespace): "
                  f"**{len(silent)}** without a handler\n\n")

        out.write("## Declared inbound messages with no handler\n\n")
        if declared_unhandled:
            for name in declared_unhandled:
                out.write(f"- `{name}`\n")
        else:
            out.write("_None._\n")

        out.write("\n## Client request types with no handler\n\n")
        out.write("These are message classes the client can send (its `outgoing` "
                  "namespaces, plus anything already in `InboundMsg`). Each one currently "
                  "ends in `No handler registered for message: ...`.\n\n")
        for name in silent:
            shape = requests.get(name) or next(
                (data for full, data in requests.items() if simple(full) == name), {})
            keys = ", ".join(shape) if shape else "(no payload fields)"
            out.write(f"- **{name}** — {keys}\n")

        out.write("\n## Server response types (for reference)\n\n")
        responses = sorted({simple(full) for full in catalogue
                            if not looks_like_request(full, inbound)} - outbound)
        for name in responses:
            out.write(f"- `{name}`\n")
        out.write("\nJSON shapes for every message above are in "
                  "`notes/client-protocol.md` / `client-protocol.json`.\n")

    print(f"wrote {OUT}: {len(silent)} unanswered request types, "
          f"{len(declared_unhandled)} declared inbound gaps")


if __name__ == "__main__":
    main()
